import { useEffect, useRef, useState } from "react";
import * as QRCode from "qrcode";
import { QrImage } from "./QrImage";
import { Body, Button } from "./Primitives.web";
import { colors } from "../lib/colors";
async function copyText(text: string) {
  try { const { writeText } = await import("@tauri-apps/plugin-clipboard-manager"); await writeText(text); }
  catch { await navigator.clipboard.writeText(text); }
}
import { listSecureDevices, revokeSecureDevice, type SecureDevice } from "../lib/api";
import { isSecureConnection, useSecureConnectionStatus } from "../lib/secureTransport";
import { rem } from "../lib/rem";

/** Codes are generated by a local native command, never by a relay-served UI. */
export function SecurePairingPanel({ baseUrl, managed = false, auto = false }: {
  baseUrl?: string;
  managed?: boolean;
  /** Onboarding (D4): the code is just there, and replaces itself when it expires. */
  auto?: boolean;
}) {
  const [pairing, setPairing] = useState<{
    pairing_uri: string; hub_url: string; expires_at: number;
    connection_check?: { identity_verified: boolean; handshake_ms: number | null; legacy_routes_hidden: boolean };
  } | null>(null);
  const requestId = useRef(0);
  const qrElement = useRef<HTMLDivElement>(null);
  const [qr, setQr] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [now, setNow] = useState(Date.now());
  useEffect(() => {
    requestId.current++; setPairing(null); setQr(""); setError(null); setBusy(false);
    return () => { requestId.current++; };
  }, [baseUrl]);
  useEffect(() => {
    if (!pairing) return;
    const timer = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(timer);
  }, [pairing]);
  useEffect(() => { if (qr) qrElement.current?.scrollIntoView({ block: "nearest" }); }, [qr]);
  const expired = pairing !== null && now >= pairing.expires_at;
  const generate = async () => {
    const id = ++requestId.current;
    setBusy(true); setError(null); setPairing(null); setQr("");
    try {
      const { invoke } = await import("@tauri-apps/api/core");
      const next = await invoke<NonNullable<typeof pairing>>("hub_pair", { baseUrl: baseUrl ?? null });
      if (id !== requestId.current) return;
      const svg = await QRCode.toString(next.pairing_uri, { type: "svg", margin: 4, color: { dark: "#0c0c0b", light: "#ffffff" } });
      if (id !== requestId.current) return;
      setNow(Date.now()); setPairing(next); setQr(svg);
    } catch (cause) { if (id === requestId.current) setError(String(cause)); }
    finally { if (id === requestId.current) setBusy(false); }
  };
  const stale = pairing === null || expired;
  useEffect(() => {
    if (auto && stale && !busy && !error) void generate();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [auto, stale, busy, error, baseUrl]);
  if (auto) {
    const left = pairing ? Math.max(0, Math.ceil((pairing.expires_at - now) / 1000)) : 0;
    const clock = `${Math.floor(left / 60)}:${String(left % 60).padStart(2, "0")}`;
    return <div data-testid="secure-pairing-panel" className="odk-setup-pair">
      <div style={{ flexShrink: 0, width: 208, height: 208, boxSizing: "border-box", display: "flex", alignItems: "center", justifyContent: "center", padding: 12, background: "#ffffff", borderRadius: 4, border: `1px solid ${colors.lineSoft}` }}>
        {qr && !expired ? <QrImage svg={qr} size={184} label="Encrypted device pairing QR code" /> : <span role="status" style={{ fontSize: rem(12), color: "#0c0c0b" }}>Creating a code…</span>}
      </div>
      <div style={{ flex: "1 1 220px", minWidth: 0, display: "flex", flexDirection: "column", gap: 10 }}>
        <div style={{ fontFamily: "var(--font-display)", fontSize: rem(20), fontWeight: 600, letterSpacing: "-0.02em" }}>Scan it with the app</div>
        <Body size={14}>Open Offdesk Dev on your phone and tap <span style={{ color: colors.fg0 }}>Scan the code</span>. Use the app’s scanner, not the camera.</Body>
        {managed ? <Body size={13} style={{ overflowWrap: "anywhere" }}>Offdesk (offdesk.so) · {baseUrl}</Body> : null}
        <div role="status" style={{ marginTop: 6, display: "flex", flexDirection: "column", gap: 6, fontFamily: "var(--font-display)", fontSize: rem(12) }}>
          {pairing?.connection_check?.identity_verified ? <span style={{ color: colors.fg2 }}>hub verified · {pairing.connection_check.handshake_ms} ms handshake</span> : null}
          {pairing && !expired ? <span style={{ color: colors.fg3 }}>new code in {clock}</span> : null}
        </div>
        {error ? <>
          <Body size={13} style={{ color: colors.err }}><span role="alert">{error}</span></Body>
          <div><Button size="sm" kind="secondary" onClick={() => void generate()}>Try again</Button></div>
        </> : null}
        {pairing && !expired ? <div style={{ display: "flex", flexWrap: "wrap", gap: 12, fontFamily: "var(--font-display)", fontSize: rem(12) }}>
          <button type="button" className="odk-text-btn" style={{ padding: 0 }} onClick={() => void copyText(pairing.pairing_uri).catch(() => setError("Could not copy the pairing link"))}>copy pairing link</button>
          <details style={{ minWidth: 0 }}><summary style={{ cursor: "pointer", color: colors.fg3, paddingTop: 7 }}>compare hub identity</summary><code style={{ display: "block", overflowWrap: "anywhere", fontSize: rem(12) }}>{new URL(pairing.pairing_uri).searchParams.get("key")}</code><Body size={12}>Check this identity on your phone before confirming the pairing.</Body></details>
        </div> : null}
      </div>
    </div>;
  }
  return <div data-testid="secure-pairing-panel" style={{ width: "100%", display: "flex", flexDirection: "column", alignItems: "center", gap: 12, paddingTop: 4 }}>
    <div style={{ fontFamily: "var(--font-display)", fontSize: rem(14), fontWeight: 600 }}>End-to-end encrypted connection</div>
    <Body size={13} style={{ textAlign: "center" }}>For the iPhone or Android app. Create a pairing code below, then choose Scan QR Code in Offdesk. Your terminal content is end-to-end encrypted. Use the app’s scanner, not your phone’s camera.</Body>
    {managed ? <Body size={13} style={{ textAlign: "center", overflowWrap: "anywhere" }}>Offdesk (offdesk.so) · {baseUrl}</Body> : null}
    {pairing && !expired && qr ? <>
      {pairing.connection_check?.identity_verified ? <div role="status" style={{ textAlign: "center" }}>
        <Body size={13}>Hub verified · {pairing.connection_check.handshake_ms} ms handshake from this Mac</Body>
        {!pairing.connection_check.legacy_routes_hidden ? <Body size={12}>This address may also serve ordinary web connections. Use a dedicated encrypted address for a managed tunnel.</Body> : null}
      </div> : null}
      <div ref={qrElement} style={{ width: 242, maxWidth: "100%", background: "#ffffff", padding: 12, borderRadius: 4, border: `1px solid ${colors.lineSoft}` }}><QrImage svg={qr} size={216} label="Encrypted device pairing QR code" /></div>
      <Body size={12} style={{ overflowWrap: "anywhere", maxWidth: "100%", textAlign: "center" }}>{pairing.hub_url}</Body>
      <details style={{ maxWidth: "100%", textAlign: "center" }}><summary style={{ cursor: "pointer", minHeight: 44, padding: 10, fontFamily: "var(--font-display)", fontSize: rem(13) }}>compare hub identity</summary><code style={{ display: "block", overflowWrap: "anywhere", fontSize: rem(12) }}>{new URL(pairing.pairing_uri).searchParams.get("key")}</code><Body size={12}>Check this identity on your phone before confirming the pairing.</Body></details>
      <Body size={12}>Expires in {Math.ceil((pairing.expires_at - now) / 1000)} seconds. Keep this code private.</Body>
      <Button kind="secondary" onClick={() => void copyText(pairing.pairing_uri).catch(() => setError("Could not copy the pairing link"))}>Copy pairing link</Button>
    </> : null}
    {expired ? <Body size={13}>This code has expired.</Body> : null}
    {error ? <Body size={13} style={{ color: colors.err }}><span role="alert">{error}</span></Body> : null}
    <Button kind="secondary" disabled={busy} onClick={() => void generate()}>{busy ? "Checking connection…" : pairing ? "Create a new pairing code" : "Pair an encrypted device"}</Button>
  </div>;
}

export function SecureDevicesPanel() {
  const secureStatus = useSecureConnectionStatus();
  const [devices, setDevices] = useState<SecureDevice[]>([]);
  const [loaded, setLoaded] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState<string | null>(null);
  const refresh = () => listSecureDevices().then((next) => { setDevices(next); setLoaded(true); }).catch((cause) => setError(String(cause)));
  useEffect(() => { void refresh(); }, []);
  const revoke = async (id: string) => {
    setBusy(id); setError(null);
    try { await revokeSecureDevice(id); await refresh(); }
    catch (cause) { setError(String(cause)); }
    finally { setBusy(null); }
  };
  const current = secureStatus?.device_id;
  return <div style={{ display: "flex", flexDirection: "column", gap: 12 }}>
    {isSecureConnection() ? <Body size={14}>End-to-end encrypted · {secureStatus?.endpoint.hub_url}</Body> : <Body size={13}>Devices paired for end-to-end encryption. Revoking a device closes its encrypted connections.</Body>}
    {loaded && devices.length === 0 ? <Body size={13}>No encrypted devices paired yet.</Body> : null}
    {devices.map((device) => <div key={device.id} style={{ display: "flex", gap: 12, alignItems: "center", flexWrap: "wrap" }}>
      <span style={{ flex: 1, fontSize: rem(14), overflowWrap: "anywhere" }}>{device.name}{device.id === current ? " (this device)" : ""}{device.revoked_at ? " · Revoked" : ""}</span>
      {!device.revoked_at ? <Button kind="ghost" disabled={busy !== null || device.id === current} onClick={() => void revoke(device.id)}>{busy === device.id ? "Revoking…" : "Revoke"}</Button> : null}
    </div>)}
    {current ? <Body size={12}>To revoke this device, use another paired device or the Hub's local Settings.</Body> : null}
    {error ? <Body size={13} style={{ color: colors.err }}><span role="alert">{error}</span></Body> : null}
  </div>;
}
